import { chromium } from "@playwright/test";
const BASE = "https://optical-management-dashboard.vercel.app";
const OUT = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
await page.goto(`${BASE}/login`);
await page.getByLabel("Email").fill("owner@lensmere.example");
await page.getByLabel("Password").fill("Lensmere-demo-2026");
await page.getByRole("button", { name: "Sign in", exact: true }).click();
await page.waitForURL(/\/app(\/|$|\?)/, { timeout: 60000 });
await page.goto(`${BASE}/app/settings?tab=integrations&ghl=overview`, { waitUntil: "networkidle", timeout: 90000 });
await page.getByRole("button", { name: "Check access" }).click();
await page.getByRole("cell", { name: "Sub-account" }).waitFor({ timeout: 90000 });
const access = await page.locator("table").filter({ hasText: "Scope" }).first().innerText();
console.log("=== ACCESS CHECK (live) ===\n" + access);
await page.screenshot({ path: `${OUT}/live-access.png`, fullPage: true });
await page.goto(`${BASE}/app/settings?tab=integrations&ghl=mapping`, { waitUntil: "networkidle", timeout: 90000 });
await page.getByRole("button", { name: "Create or map pipelines" }).click();
await page.getByText(/created now|already existed/).first().waitFor({ timeout: 120000 }).catch(() => {});
await page.waitForTimeout(1500);
const card = await page.locator("main").innerText();
const i = card.indexOf("Optical pipelines");
console.log("\n=== PIPELINES (live) ===\n" + card.slice(i, i + 1500));
await page.screenshot({ path: `${OUT}/live-pipelines.png`, fullPage: true });
await browser.close();
