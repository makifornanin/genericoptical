import { chromium } from "@playwright/test";
const BASE = "https://optical-management-dashboard.vercel.app";
const OUT = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1400 } });
await page.goto(`${BASE}/login`);
await page.getByLabel("Email").fill("owner@lensmere.example");
await page.getByLabel("Password").fill("Lensmere-demo-2026");
await page.getByRole("button", { name: "Sign in", exact: true }).click();
await page.waitForURL(/\/app(\/|$|\?)/, { timeout: 60000 });
await page.goto(`${BASE}/app/settings?tab=integrations&ghl=mapping`, { waitUntil: "networkidle", timeout: 90000 });
await page.getByRole("button", { name: "Create or map pipelines" }).click();
await page.getByText(/already existed|created now/).first().waitFor({ timeout: 120000 });
const text = await page.locator("main").innerText();
const start = text.indexOf("Lead pipeline:");
console.log(text.slice(start, text.indexOf("Sync settings", start)));
const sel = async (label) => page.getByLabel(label).evaluate((el) => el.options[el.selectedIndex]?.text);
for (const l of ["Sales pipeline", "Stage: POS sale completed", "Stage: order placed", "Stage: payment pending", "Stage: order processing", "Stage: order ready for pickup", "Stage: order handed over", "Lead pipeline", "Lead stage: New lead", "Lead stage: Contacted", "Lead stage: Qualified", "Lead stage: Appointment scheduled", "Lead stage: Follow-up", "Lead stage: Converted"]) console.log(`${l} → ${await sel(l).catch(() => "?")}`);
const sync = {};
for (const l of ["Contacts & leads", "Opportunities", "POS sales → CRM", "Products", "Inventory", "Appointments", "Online orders"]) sync[l] = await page.getByLabel(l, { exact: true }).isChecked().catch(() => "?");
console.log("sync areas:", JSON.stringify(sync));
await page.screenshot({ path: `${OUT}/live-pipelines-mapped.png`, fullPage: true });
await browser.close();
