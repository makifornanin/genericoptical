import { chromium } from "@playwright/test";
const SITE = "https://optical-customer-website.vercel.app";
const BASE = "https://optical-management-dashboard.vercel.app";
const OUT = process.argv[2];
const stamp = process.argv[3];
const name = `Optical Sync Test ${stamp}`;
const email = `optical.sync.test+${stamp}@example.com`;
const browser = await chromium.launch();
// 1. Inquiry on the live website (real public path).
const site = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await site.goto(`${SITE}/contact`, { waitUntil: "networkidle" });
await site.locator('[name="fullName"]').fill(name);
await site.locator('[name="email"]').fill(email);
await site.locator('[name="phone"]').fill("0917 555 01" + stamp.slice(-2));
await site.locator('[name="message"]').fill("Live GHL sync test from the staging website. Safe to ignore.");
await site.locator('form button[type="submit"]').click();
await site.waitForTimeout(4000);
console.log("website inquiry:", (await site.locator("main").innerText()).match(/thank|received|sent/i) ? "accepted" : "UNCLEAR");
// 2. Dashboard: run the sync worker, then read the log.
const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
await page.goto(`${BASE}/login`);
await page.getByLabel("Email").fill("owner@lensmere.example");
await page.getByLabel("Password").fill("Lensmere-demo-2026");
await page.getByRole("button", { name: "Sign in", exact: true }).click();
await page.waitForURL(/\/app(\/|$|\?)/, { timeout: 60000 });
await page.goto(`${BASE}/app/settings?tab=integrations&ghl=overview`, { waitUntil: "networkidle", timeout: 90000 });
await page.getByRole("button", { name: "Sync now" }).click();
const toast = page.locator("[data-sonner-toast]").first();
await toast.waitFor({ timeout: 120000 });
console.log("sync now:", (await toast.innerText()).replace(/\n/g, " "));
await page.goto(`${BASE}/app/settings?tab=integrations&ghl=log`, { waitUntil: "networkidle", timeout: 90000 });
const rows = await page.locator("table tbody tr").all();
console.log("=== SYNC LOG (latest) ===");
for (const r of rows.slice(0, 6)) console.log((await r.innerText()).replace(/\s*\n\s*/g, " | ").slice(0, 300));
await page.goto(`${BASE}/app/leads?q=${encodeURIComponent(email)}`, { waitUntil: "networkidle", timeout: 90000 });
const leadsText = await page.locator("main").innerText();
console.log("lead in dashboard:", leadsText.includes(name));
const link = page.locator("a[href^='/app/leads/']").filter({ hasText: name }).first();
console.log("LEAD_URL=" + (await link.getAttribute("href").catch(() => "")));
await page.goto(`${BASE}/app/pipeline`, { waitUntil: "networkidle", timeout: 90000 });
const pt = await page.locator("main").innerText();
const at = pt.indexOf(name);
console.log("=== CRM PIPELINE PAGE ===\n" + (at >= 0 ? pt.slice(Math.max(0, at - 300), at + 200) : pt.slice(0, 1200)));
await page.screenshot({ path: `${OUT}/live-pipeline-page.png`, fullPage: true });
await browser.close();
