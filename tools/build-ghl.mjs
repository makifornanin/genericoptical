#!/usr/bin/env node
/*
 * Builds ghl-ready/: copy-paste snippets for GoHighLevel, generated from the source files.
 *   node tools/build-ghl.mjs                 → ghl-ready/
 *   node tools/build-ghl.mjs --out=some/dir  → elsewhere (used by the tests)
 *
 * Two install variants are produced (see ghl-setup-guide.md → "Install the code"):
 *  - ghl-ready/site/ + ghl-ready/pages/ : EVERYTHING PASTED into GHL (no other hosting needed).
 *      The global CSS rides in the header section's Custom Code element, the config and core script
 *      in the footer section's element, and each page gets its own CSS + blocks + page-script element.
 *  - ghl-ready/hosted/ : SMALL TAGS for GHL tracking code, pointing at the same files uploaded to a
 *      static host (use this if GHL rejects or truncates large code elements).
 * Scripts are always placed at the top level of a snippet, never inside a <div> (GHL does not run
 * scripts nested in elements).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, "").split("=")));
const OUT = resolve(ROOT, args.out || "ghl-ready");
const read = (...p) => readFileSync(join(ROOT, ...p), "utf8");
const manifest = JSON.parse(read("pages", "pages.json")).pages;

const FONTS = `<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter+Tight:wght@400;500;600;700&family=Instrument+Sans:wght@500;600;700&display=swap">`;
const banner = (what, where) => `<!--\n  ${what}\n  WHERE: ${where}\n  Generated by tools/build-ghl.mjs from the source files — edit the sources, then re-run it.\n-->\n`;
// A literal "</script" or "</style" inside the code (even in a comment) would end the tag early in
// the browser, so it is escaped defensively.
const script = (src) => `<script>\n${src.trim().replace(/<\/script/gi, "<\\/script")}\n</script>\n`;
const style = (src) => `<style>\n${src.trim().replace(/<\/style/gi, "<\\/style")}\n</style>\n`;

if (existsSync(OUT)) rmSync(OUT, { recursive: true, force: true });
const write = (rel, text) => {
  const file = join(OUT, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
};

/* ── Site-wide (pasted) ─────────────────────────────────────────────── */
write("site/A-head-tracking-code.html", banner("Fonts for every page.", "Sites → Websites → (site) → Settings → Head tracking code") + FONTS + "\n");
write(
  "site/B-header-section.html",
  banner(
    "GLOBAL STYLES + HEADER. One Custom Code element in the header section, saved as a Universal (or Global) section.",
    "Section 1 of every page. Section/row/column: full width, padding 0, no background.",
  ) +
    style(read("styles", "oc-base.css")) +
    read("components", "header.html").trim() +
    "\n",
);
write(
  "site/C-footer-section.html",
  banner(
    "FOOTER + BUSINESS CONFIG + CORE SCRIPT. One Custom Code element in the footer section, saved as a Universal (or Global) section.",
    "Last section of every page. Edit the OC_CONFIG values (scripts/oc-config.js) before pasting.",
  ) +
    read("components", "footer.html").trim() +
    "\n" +
    script(read("scripts", "oc-config.js")) +
    script(read("scripts", "oc-site.js")),
);

/* ── Site-wide (hosted variant) ─────────────────────────────────────── */
const HOST = "https://YOUR-FILE-HOST/optical-site/";
write(
  "hosted/A-head-tracking-code.html",
  banner("Fonts + global styles from your file host. Replace YOUR-FILE-HOST with the real folder URL.", "Settings → Head tracking code") +
    FONTS +
    `\n<link rel="stylesheet" href="${HOST}styles/oc-base.css">\n`,
);
write(
  "hosted/B-body-tracking-code.html",
  banner("Business config + core script from your file host. Replace YOUR-FILE-HOST.", "Settings → Body tracking code") +
    `<script src="${HOST}scripts/oc-config.js"></script>\n<script src="${HOST}scripts/oc-site.js"></script>\n`,
);
write(
  "hosted/C-header-section.html",
  banner("HEADER markup only (styles come from the hosted oc-base.css).", "Custom Code element in a Universal header section") + read("components", "header.html").trim() + "\n",
);
write(
  "hosted/D-footer-section.html",
  banner("FOOTER markup only (scripts come from the body tracking code).", "Custom Code element in a Universal footer section") + read("components", "footer.html").trim() + "\n",
);

/* ── Pages ──────────────────────────────────────────────────────────── */
const rows = [];
for (const page of manifest) {
  const dir = join(ROOT, "pages", page.id);
  const blocks = readdirSync(join(dir, "blocks")).filter((f) => f.endsWith(".html")).sort();
  const hasCss = existsSync(join(dir, `${page.id}.css`));
  const hasJs = existsSync(join(dir, `${page.id}.js`));
  const files = [];
  if (hasCss) {
    write(`pages/${page.id}/00-page-custom-css.css`, read("pages", page.id, `${page.id}.css`));
    files.push("00-page-custom-css.css → page Settings → Custom CSS");
  }
  for (const b of blocks) {
    write(`pages/${page.id}/${b}`, read("pages", page.id, "blocks", b));
    files.push(`${b} → Custom Code element`);
  }
  if (hasJs || page.catalogue) {
    write(
      `pages/${page.id}/99-page-script.html`,
      banner(`PAGE SCRIPT for ${page.name}.`, "A Custom Code element in the last section before the footer (or this page's Footer tracking code).") +
        (page.catalogue ? script(read("scripts", "oc-catalogue.js")) : "") +
        (hasJs ? script(read("pages", page.id, `${page.id}.js`)) : ""),
    );
    files.push("99-page-script.html → Custom Code element at the bottom");
    if (page.catalogue || hasJs) {
      write(
        `hosted/pages/${page.id}-footer-tracking-code.html`,
        banner(`PAGE SCRIPT tags for ${page.name}.`, "This page → Settings → Tracking code → Footer") +
          (page.catalogue ? `<script src="${HOST}scripts/oc-catalogue.js"></script>\n` : "") +
          (hasJs ? `<script src="${HOST}pages/${page.id}/${page.id}.js"></script>\n` : ""),
      );
    }
  }
  rows.push({ page, files });
}

/* ── Index ──────────────────────────────────────────────────────────── */
const index = `# GHL-ready snippets

Generated by \`node tools/build-ghl.mjs\` from the source files. Don't edit these copies: change the
sources (\`styles/\`, \`scripts/\`, \`components/\`, \`pages/\`), then re-run the tool.

Follow **ghl-setup-guide.md** for the full walkthrough. Paste order:

## Site-wide (once)

| File | Paste into |
|---|---|
| \`site/A-head-tracking-code.html\` | Website → Settings → Head tracking code |
| \`site/B-header-section.html\` | Custom Code element in the **header section** → save it as a Universal (or Global) section |
| \`site/C-footer-section.html\` | Custom Code element in the **footer section** → save it as a Universal (or Global) section |

Using hosted files instead (if GHL truncates or rejects large code)? Use \`hosted/\` (see the guide).

## Pages

${rows
  .map(
    ({ page, files }) => `### ${page.name} — \`${page.path}\`

- SEO title: ${page.title}
- SEO description: ${page.description}${page.noindex ? "\n- Custom meta tag: `robots` = `noindex` (hide from search engines)" : ""}
- Instructions: \`pages/${page.id}/README.md\`

${files.map((f) => `1. \`pages/${page.id}/${f.split(" → ")[0]}\` → ${f.split(" → ")[1]}`).join("\n")}
`,
  )
  .join("\n")}`;
write("README.md", index);
console.log(`ghl-ready written to ${OUT}`);
